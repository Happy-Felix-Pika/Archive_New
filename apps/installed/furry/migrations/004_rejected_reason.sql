-- Чому пост у відхилених:
--   'auto'     — архіватор сам відкинув як копію з іншого сайту;
--   'manual'   — людина натисла «Дублікат» / масове відхилення;
--   'replaced' — старий файл, замінений новим (його качати не можна);
--   NULL       — записано до появи цієї колонки, причина невідома.
-- «Перевірити пули» очищає лише 'auto' і NULL — ручні рішення лишаються.
ALTER TABLE rejected_duplicates
    ADD COLUMN IF NOT EXISTS reason VARCHAR(16) NULL;
